    record Context(boolean authorized, List<String> blocked, GitHubRepoRef repo, AssessmentFindingDto finding, String validation) {}

    Context context(RepairJobEntity job, AuthenticatedUser user) {
        List<String> blocked = new ArrayList<>();
        boolean authorized = user != null && (user.role() == Role.ADMIN || approverEmails.contains(user.email().toLowerCase(Locale.ROOT)));
        if (!authorized) blocked.add("Your account is not allowed to apply remediations to GitHub (requires the ADMIN role or RELAY_GITHUB_REMEDIATION_APPROVERS).");
        if (!github.configured()) blocked.add("GitHub remediation is not configured.");
        GitHubRepoRef repo = GitHubRepoRef.parse(job.repository).orElse(null);
        if (repo == null) blocked.add("The patch repository is not a supported github.com repository URL.");
        else if (!allowedRepositories.contains(repo.key())) blocked.add("Repository " + repo.fullName() + " is not enabled for GitHub remediation (RELAY_GITHUB_REMEDIATION_REPOSITORIES).");
        AssessmentFindingDto finding = null;
        if (job.assessmentId == null || job.findingId == null || job.strategy == null || job.patchText == null) {
            blocked.add("Only patch proposals generated from an assessment finding can be applied.");
        } else if (!PatchProposalService.PROPOSED.equals(job.state)) {
            blocked.add("The patch proposal is not in a reviewable state.");
        } else {
            AssessmentEntity assessment = assessments.findById(job.assessmentId).orElse(null);
            if (assessment == null) blocked.add("The assessment for this patch no longer exists.");
            else {
                if (!job.repository.equals(assessment.getRepositoryUrl()) || !job.commitSha.equals(assessment.getRepositoryCommit())) {
                    blocked.add("The patch does not belong to the repository and commit of its assessment.");
                }
                finding = findings(assessment).stream().filter(f -> job.findingId.equals(f.id())).findFirst().orElse(null);
                if (finding == null) blocked.add("The patch does not belong to a finding of its assessment.");
                else if (!job.findingTitle.equals(finding.title()) || !finding.file().equals(job.filePath) || !GitSourceFetcher.isSafeRelativePath(finding.file())) {
                    blocked.add("The patch does not match its finding.");
                }
            }
        }
        String validation = validation(job);
        if (validation == null) blocked.add("Only sandbox-validated patches can be applied (validation: " + job.verificationStatus + ").");
        return new Context(authorized, blocked, repo, finding, validation);
    }

    /** "passed", "preexisting_test_failures" (build + security re-scan passed, tests fail identically without the patch), or null. */
    public String validation(RepairJobEntity job) {
        if ("passed".equals(job.verificationStatus)) return VALIDATION_PASSED;
        Map<String, String> checks = checks(job);
        if ("passed".equals(checks.get("Patch applied")) && "passed".equals(checks.get("Build")) && "passed".equals(checks.get("Security re-scan"))
                && "failed".equals(checks.get("Tests")) && "failed".equals(checks.get("Baseline tests"))) {
            return VALIDATION_PREEXISTING;
        }
        return null;
    }

    private Map<String, String> checks(RepairJobEntity job) {
        try {
            List<RepairCheckDto> list = mapper.readValue(job.checksJson == null ? "[]" : job.checksJson, new TypeReference<List<RepairCheckDto>>() {});
            return list.stream().collect(Collectors.toMap(RepairCheckDto::name, RepairCheckDto::status, (a, b) -> a));
        } catch (Exception ex) {
            return Map.of();
        }
    }

    private List<AssessmentFindingDto> findings(AssessmentEntity assessment) {
        try { return mapper.readValue(assessment.getFindingsJson(), new TypeReference<List<AssessmentFindingDto>>() {}); }
        catch (Exception ex) { return List.of(); }
    }

    // ---- Text ---------------------------------------------------------------------------------------------------

    static String shortTitle(String findingTitle) {
        String title = findingTitle == null ? "finding" : findingTitle.toLowerCase(Locale.ROOT);
        return title.startsWith("possible ") ? title.substring("possible ".length()) : title;
    }

    static String commitMessage(RepairJobEntity job) {
        return "fix: remediate " + shortTitle(job.findingTitle) + " detected by RELAY AEGIS\n\n"
                + "Finding: " + job.findingId + "\nPatch: " + job.id + "\nStrategy: " + job.strategy + "\nAssessed commit: " + job.commitSha + "\n";
    }

    static String pullRequestTitle(RepairJobEntity job) {
        return "fix: remediate " + shortTitle(job.findingTitle) + " [RELAY AEGIS]";
    }

    String pullRequestBody(RepairJobEntity job, GitHubRemediationEntity record, Context context) {
        Map<String, String> checks = checks(job);
        StringBuilder body = new StringBuilder("## RELAY AEGIS Remediation\n\n")
                .append("**Finding:** ").append(job.findingTitle).append("\n")
                .append("**Finding ID:** ").append(job.findingId).append("\n")
                .append("**File:** `").append(job.filePath).append("`\n")
                .append("**Patch:** ").append(job.id).append(" (strategy `").append(job.strategy).append("`)\n")
                .append("**Assessed commit:** ").append(job.commitSha).append("\n")
                .append("**Repository:** ").append(record.repository).append("\n\n")
                .append("### Sandbox validation\n");
        for (String name : List.of("Sandbox checkout", "Patch applied", "Build", "Tests", "Baseline tests", "Security re-scan")) {
            if (checks.containsKey(name)) body.append("- ").append(name).append(": ").append(checks.get(name)).append("\n");
        }
        if (VALIDATION_PREEXISTING.equals(context.validation())) {
            body.append("\n> The tests fail both with and without this patch (pre-existing or environment failure). ")
                .append("The approver acknowledged this before the pull request was opened.\n");
        }
        body.append("\n### Important\nThis pull request was generated by RELAY AEGIS from a deterministic patch strategy. ")
            .append("It was not merged. Review it, and rotate any exposed credential with its issuer, before merging.\n");
        return body.toString();
    }

    // ---- Persistence helpers ------------------------------------------------------------------------------------

    private RepairJobEntity job(String patchId) {
        return repairs.findById(patchId).orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Patch proposal not found."));
    }

    private Optional<GitHubRemediationEntity> latest(String patchId) {
        return remediations.findByRepairJobIdOrderByCreatedAtDesc(patchId).stream().findFirst();
    }

    private GitHubRemediationEntity fail(GitHubRemediationEntity record, String stage, String code, String message) {
        record.status = GitHubRemediationEntity.FAILED;
        record.failedStage = stage;
        record.errorCode = code;
        record.errorMessage = message;
        return save(record);
    }

    private GitHubRemediationEntity save(GitHubRemediationEntity record) {
        record.updatedAt = Instant.now();
        return remediations.save(record);
    }

    GitHubRemediationDto toDto(GitHubRemediationEntity e) {
        return new GitHubRemediationDto(e.id, e.repairJobId, e.status, e.repository, e.baseBranch, e.branch, e.commitSha, e.prNumber, e.prUrl,
                e.validationStatus, e.preexistingFailuresAcknowledged, e.failedStage, e.errorCode, e.errorMessage,
                e.verificationStatus, e.verificationDetail, e.createdAt, e.updatedAt);
    }
