import { useState } from 'react';
import { useQuery } from '@tanstack/react-query';
import { ArrowLeft, CheckSquare, Copy, Download, Printer } from 'lucide-react';
import { Link, useParams } from 'react-router-dom';
import { PageHeader } from '@/components/layout/PageHeader';
import { Panel } from '@/components/common/Panel';
import { ErrorState, LoadingState } from '@/components/feedback/States';
import { apiDownload, apiGet } from '@/lib/api/client';
import { formatDuration } from '@/lib/duration';
import type { PostIncidentReport } from '@/types/domain';

const time = (at: string | null) => (at ? new Date(at).toLocaleString() : 'Not recorded');

/** Blameless post-incident report: generated from stored evidence, printable to PDF, downloadable as Markdown. */
export function IncidentReportPage() {
  const { id = '' } = useParams();
  const [notice, setNotice] = useState('');
  const report = useQuery({ queryKey: ['incident-report', id], queryFn: () => apiGet<PostIncidentReport>(`/api/incidents/${id}/report`) });
  if (report.isLoading) return <LoadingState label="Building report" />;
  if (report.isError || !report.data) return <ErrorState title="Report unavailable" detail={report.error?.message ?? 'The report could not be built.'} onRetry={() => void report.refetch()} />;
  const r = report.data.data;
  const copy = async () => {
    try { await navigator.clipboard.writeText(r.markdown); setNotice('Markdown copied. Paste it into your wiki or ticket.'); }
    catch { setNotice('Copy is blocked in this browser. Use Download Markdown instead.'); }
  };
  const download = () => apiDownload(`/api/incidents/${id}/report.md`, `${id}-report.md`).catch((error: Error) => setNotice(error.message));
  return <div className="report-page">
    <PageHeader title="Post-incident report" description={`${r.incidentId} · ${r.title}`} actions={<div className="report-actions no-print">
      <Link className="btn" to={`/incidents/${id}`}><ArrowLeft size={13} /> Incident</Link>
      <button className="btn" onClick={() => void copy()}><Copy size={13} /> Copy Markdown</button>
      <button className="btn" onClick={() => void download()}><Download size={13} /> Download Markdown</button>
      <button className="btn btn-primary" onClick={() => window.print()}><Printer size={13} /> Print or save PDF</button>
    </div>} />
    {notice ? <div className="info-box no-print" role="status" style={{ marginBottom: 14 }}>{notice}</div> : null}
    <p className="report-note">Blameless report generated by RELAY AEGIS from stored evidence on {time(r.generatedAt)}. Nothing here was written by AI; anything RELAY did not record says so.</p>
    <div className="metric-grid report-facts">
      <Fact label="Outcome" value={r.outcome} />
      <Fact label="Time to detect" value={formatDuration(r.detectionMs)} />
      <Fact label="Time to recover" value={formatDuration(r.recoveryMs)} />
      <Fact label="Failure type" value={r.failureType} mono />
    </div>
    <Panel title="Summary" subtitle={`${r.application} · ${r.component} · ${r.severity} · detected ${time(r.detectedAt)}`}>
      <p className="report-text">{r.summary ?? 'Not recorded.'}</p>
    </Panel>
    <Panel title="Root cause" subtitle={`Confidence ${r.confidence} · diagnosed by ${r.diagnosisSource}`}>
      <p className="report-text">{r.rootCause}</p>
    </Panel>
    <Panel title="Timeline" subtitle="Every recorded step, oldest first" bodyClassName="panel-body-tight">
      <div className="table-scroll"><table className="app-table"><thead><tr><th>Time</th><th>Event</th><th>Detail</th></tr></thead>
        <tbody>{r.timeline.map((e, i) => <tr key={`${e.label}-${i}`}><td className="tabular nowrap">{time(e.at)}</td><td>{e.label}</td><td className="app-meta">{e.detail}</td></tr>)}</tbody></table></div>
    </Panel>
    <Panel title="Actions taken" subtitle="From the durable action journal" bodyClassName="panel-body-tight">
      {r.actions.length ? <div className="table-scroll"><table className="app-table"><thead><tr><th>#</th><th>Action</th><th>Target</th><th>Started by</th><th>Policy</th><th>Result</th></tr></thead>
        <tbody>{r.actions.map((a) => <tr key={`${a.attempt}-${a.at}`}><td>{a.attempt}</td><td className="mono">{a.action}</td><td className="mono">{a.target}</td><td>{a.automatic ? 'Policy (automatic)' : 'Operator approval'}</td><td className="mono">{a.policy}</td><td>{a.verification ?? a.phase}</td></tr>)}</tbody></table></div>
        : <p className="report-text" style={{ padding: 14 }}>No recovery action was run.</p>}
    </Panel>
    <Panel title="Verification"><p className="report-text">{r.verification}</p></Panel>
    <Panel title="Evidence" subtitle="Observed facts and the diagnosis's supporting evidence">
      {r.evidence.length ? <ul className="report-list">{r.evidence.map((e) => <li key={e}>{e}</li>)}</ul> : <p className="report-text">No observed evidence was stored.</p>}
    </Panel>
    <Panel title="Follow-ups" subtitle={r.similarIncidents30d ? `This failure happened ${r.similarIncidents30d} other time(s) in 30 days` : 'Derived from what the records show'}>
      <ul className="report-list followups">{r.followUps.map((f) => <li key={f}><CheckSquare size={14} /> <span>{f}</span></li>)}</ul>
    </Panel>
  </div>;
}

function Fact({ label, value, mono }: { label: string; value: string; mono?: boolean }) {
  return <div className="panel compact-stat"><div className="compact-label">{label}</div><div className={`report-fact${mono ? ' mono' : ''}`}>{value}</div></div>;
}
